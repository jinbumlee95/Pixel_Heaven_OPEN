import assert from 'node:assert/strict';
import { Camera } from '../src/game/Camera.js';
const camera = new Camera();
camera.resize(1024, 640);
camera.center({ x: 1000, y: 980 });
assert.deepEqual(camera.bounds, { left: 984, top: 970, right: 1016, bottom: 990 });
camera.pan(0.5, 0.5);
assert.deepEqual(camera.bounds, { left: 984, top: 970, right: 1017, bottom: 991 });
camera.pan(-10000, -10000);
assert.equal(camera.x, 0);
assert.equal(camera.y, 0);
camera.pan(10000, 10000);
assert.equal(camera.bounds.right, 2000);
assert.equal(camera.bounds.bottom, 2000);
camera.resize(1440, 800);
assert.equal(camera.bounds.right, 2000);
assert.equal(camera.bounds.bottom, 2000);
assert.ok((camera.bounds.right - camera.bounds.left) * (camera.bounds.bottom - camera.bounds.top) < 2000);
console.log('camera: passed');
